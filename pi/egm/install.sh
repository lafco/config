#!/usr/bin/env bash
# Instala o Elephant-Goldfish Model (EGM) no pi.
#
# O que faz:
#   1. vendoriza google/elephant-goldfish-model num sha fixo em ./vendor
#   2. mapeia as frases de delegação das skills para a tool `subagent` nativa
#   3. gera os revisores goldfish somente-leitura em ~/.pi/agent/agents
#   4. registra ./ como pacote do pi (skills descobrem relativas ao vendor)
#
# Uso:
#   ./install.sh              instala ou atualiza
#   ./install.sh --check      verifica o estado instalado e sai != 0 em falha
#   ./install.sh --no-fetch   reaproveita o vendor existente (offline)
#   ./install.sh --uninstall  remove revisores e o pacote, mantém o vendor
set -euo pipefail

REF="${EGM_REF:-70406c4d22cc7ea8299637c2c5b44625c48b3f08}"

HERE="$(cd "$(dirname "$0")" && pwd)"
VENDOR="$HERE/vendor"
PI_DOC="$HERE/docs/pi.md"
AGENT_DIR="${PI_CODING_AGENT_DIR:-$HOME/.pi/agent}/agents"
MARKER='<!-- generated by pi/egm/install.sh; edite a persona no upstream, não este arquivo -->'
TOOLS='read, grep, find, ls'
REVIEWERS=(codebase_details comprehension design_critic implementation_readiness
           inventive_catalyst structural style zoom_out)
DOC_LINE='In Pi, read [Pi integration](../../docs/pi.md) first.'

die() { echo "erro: $*" >&2; exit 1; }

frontmatter_field() { # frontmatter_field <campo> <arquivo>
  awk -v key="$2" 'NR==1 && $0!="---" {exit} NR>1 && $0=="---" {exit}
    NR>1 && index($0, key": ")==1 {print substr($0, length(key)+3); exit}' "$1"
}

uninstall() {
  for r in "${REVIEWERS[@]}"; do
    src="$VENDOR/agents/$r.md"
    [[ -f "$src" ]] || continue
    name="$(frontmatter_field "$src" name)"
    dest="$AGENT_DIR/$name.md"
    if [[ -f "$dest" ]] && grep -qF "$MARKER" "$dest"; then
      rm -f "$dest" && echo "removido $dest"
    fi
  done
  if pi list 2>/dev/null | grep -qF "$HERE"; then
    pi remove "$HERE" && echo "pacote removido de ~/.pi/agent/settings.json"
  fi
}

fetch_vendor() {
  local tmp src
  tmp="$(mktemp -d)"
  curl -fsSL "https://codeload.github.com/google/elephant-goldfish-model/tar.gz/$REF" |
    tar -xz -C "$tmp" || die "falha ao baixar o EGM em $REF"
  src="$tmp/elephant-goldfish-model-${REF:0:7}"
  [[ -d "$src/skills" ]] || src="$(find "$tmp" -maxdepth 1 -mindepth 1 -type d | head -1)"
  rm -rf "$VENDOR"
  mkdir -p "$VENDOR"
  cp -R "$src/skills" "$src/agents" "$src/resources" "$src/docs" "$src/LICENSE" "$VENDOR/"
  cp "$PI_DOC" "$VENDOR/docs/pi.md"
  printf '%s\n' "$REF" >"$VENDOR/.egm-ref"
  rm -rf "$tmp"
  echo "vendorizado em $REF"
}

patch_skills() {
  local changed=0 skill
  for skill in "$VENDOR"/skills/*/SKILL.md; do
    grep -qF "$DOC_LINE" "$skill" && continue
    awk -v line="$DOC_LINE" '
      { print }
      !done && ($0 ~ /^In Claude Code or Cowork,/) { print line; done=1 }
    ' "$skill" >"$skill.tmp"
    grep -qF "$DOC_LINE" "$skill.tmp" || die "sem ponto de inserção em $skill"
    mv "$skill.tmp" "$skill"
    changed=$((changed + 1))
  done
  echo "skills com o mapeamento do pi: $changed alterada(s)"
}

write_package() {
  cat >"$HERE/package.json" <<'JSON'
{
  "name": "egm-for-pi",
  "private": true,
  "description": "Elephant-Goldfish Model vendorizado para o pi, com revisores goldfish locais.",
  "pi": {
    "skills": ["./vendor/skills"]
  }
}
JSON
}

generate_agents() {
  mkdir -p "$AGENT_DIR"
  local r src name description dest
  for r in "${REVIEWERS[@]}"; do
    src="$VENDOR/agents/$r.md"
    [[ -f "$src" ]] || die "persona ausente: $src"
    name="$(frontmatter_field "$src" name)"
    description="$(frontmatter_field "$src" description)"
    [[ -n "$name" && -n "$description" ]] || die "frontmatter incompleto em $src"
    dest="$AGENT_DIR/$name.md"
    if [[ -e "$dest" ]] && ! grep -qF "$MARKER" "$dest"; then
      die "$dest existe e não foi gerado por este script"
    fi
    {
      printf -- '---\nname: %s\ndescription: %s\ntools: %s\n---\n\n%s\n' \
        "$name" "$description" "$TOOLS" "$MARKER"
      printf 'Persona canônica: %s\n' "$src"
      awk 'NR==1 && $0=="---" {fm=1; next} fm && $0=="---" {fm=0; next} !fm' "$src"
    } >"$dest.tmp"
    mv "$dest.tmp" "$dest"
    echo "revisor instalado: $dest"
  done
}

register_package() {
  if pi list 2>/dev/null | grep -qF "$HERE"; then
    echo "pacote já registrado: $HERE"
  else
    pi install "$HERE"
  fi
}

check() {
  local fails=0 skill r src name dest
  [[ -f "$VENDOR/.egm-ref" ]] || { echo "FALHA vendor ausente"; return 1; }
  [[ "$(cat "$VENDOR/.egm-ref")" == "$REF" ]] || { echo "FALHA vendor em sha diferente de $REF"; fails=1; }
  for skill in "$VENDOR"/skills/*/SKILL.md; do
    grep -qF "$DOC_LINE" "$skill" || { echo "FALHA sem mapeamento do pi: $skill"; fails=1; }
  done
  pi list 2>/dev/null | grep -qF "$HERE" || { echo "FALHA pacote não registrado: $HERE"; fails=1; }
  for r in "${REVIEWERS[@]}"; do
    src="$VENDOR/agents/$r.md"
    name="$(frontmatter_field "$src" name)"
    dest="$AGENT_DIR/$name.md"
    if [[ ! -f "$dest" ]]; then echo "FALHA revisor ausente: $dest"; fails=1; continue; fi
    grep -qF "$MARKER" "$dest" || { echo "FALHA revisor sem marcador: $dest"; fails=1; }
    grep -qF "tools: $TOOLS" "$dest" || { echo "FALHA revisor sem allowlist somente-leitura: $dest"; fails=1; }
  done
  # As skills só existem como comando se o pi as descobrir pelo pacote.
  if command -v pi >/dev/null; then
    local listed
    listed="$(printf '{"id":"1","type":"get_commands"}\n' | timeout 60 pi --mode rpc --no-session 2>/dev/null || true)"
    for skill in "$VENDOR"/skills/*/SKILL.md; do
      name="$(basename "$(dirname "$skill")")"
      grep -qF "\"skill:$name\"" <<<"$listed" || { echo "FALHA skill não descoberta pelo pi: $name"; fails=1; }
    done
  fi
  ((fails == 0)) && echo "check ok: vendor $REF, $(ls "$VENDOR"/skills | wc -l) skills, ${#REVIEWERS[@]} revisores"
  return "$fails"
}

case "${1:-}" in
  --uninstall) uninstall; exit 0 ;;
  --check) check; exit $? ;;
  --no-fetch) ;;
  "") fetch_vendor ;;
  *) die "opção desconhecida: $1" ;;
esac

[[ -d "$VENDOR/skills" ]] || die "vendor ausente; rode sem --no-fetch"
patch_skills
write_package
generate_agents
register_package
echo "pronto. use /skill:egm-review <documento> numa sessão nova."
